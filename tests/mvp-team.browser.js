    await p.waitForFunction(id=>document.querySelector("#run-id").textContent.startsWith(id),ids[1]);
    await p.locator("#run-continue").click();
    check(await p.locator("#continue-model").inputValue()==="auto","不同 Session 不混用模型配置草稿");
    check(await p.locator("#continue-input").inputValue()!==first,"不同 Session 不混用需求内容");
    await p.locator("#continue-tool").selectOption("codex");
    await p.locator("#continue-model").fill("explicit-fixture-model");
    await p.locator("#continue-effort").selectOption("high");
    await p.locator("#modal-submit").click();
    await p.waitForFunction(()=>!document.querySelector("#modal").open);
    await p.waitForFunction(()=>document.querySelector("#task-list").textContent.includes("explicit-fixture-model"));
    const detail=await p.evaluate(async id=>{const r=await fetch("/v1/runs/"+id,{headers:{Authorization:"Bearer "+sessionStorage.getItem("octopus.token")}});return r.json();},ids[1]);
    check(detail.id===ids[1]&&detail.workspace.startsWith("/fixture/"),"续作保留 Run ID 和 Workspace");
    check(detail.tasks[0].spec.effort==="high"&&detail.tasks[0].attempts[0].spec.model==="auto","新的执行配置与旧 Attempt 分开保存");
    check((await p.locator("#stream-status").textContent()).includes("已连接"),"浏览器连接真实 SSE 状态流");
    await p.locator("#flow-list [data-flow]").first().click();
    await p.locator("#flow-name").fill("Fixture 编辑后的流程");
    await p.waitForTimeout(1100);
    check(await p.locator("#modal").evaluate(n=>n.open),"状态事件不会闪退工作流编辑框");
    await p.locator("#modal-submit").click();
    await p.waitForFunction(()=>!document.querySelector("#modal").open);
    await p.waitForFunction(()=>document.querySelector("#flow-list").textContent.includes("v2"));
