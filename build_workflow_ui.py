"""Bundle browser helpers into the established /workflow.js route.

Only concatenate first-party classic scripts. No npm build or dynamic loading
is required, including when an older workbench process still serves the files.
"""
from pathlib import Path
import argparse
import os
import uuid

ROOT = Path(__file__).resolve().parent
SOURCES = ("workflow-progress.js", "workflow-editor-store.js", "workflow-session-ops.js", "workflow-app.js")


def build(root=ROOT, *, check=False):
    ui = root / "ui"
    content = "// Generated by build_workflow_ui.py; edit ui/workflow-app.js and the source helpers.\n"
    for name in SOURCES:
        content += f"\n// ---- {name} ----\n" + (ui / name).read_text() + "\n"
    content = content.rstrip() + "\n"
    target = ui / "workflow.js"
    if target.exists() and target.read_text() == content:
        return target
    if check:
        raise RuntimeError("ui/workflow.js 已过期，请运行 python3 build_workflow_ui.py。")
    temporary = ui / (".workflow-" + uuid.uuid4().hex)
    temporary.write_text(content)
    os.replace(temporary, target)
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(build(check=parser.parse_args().check))
